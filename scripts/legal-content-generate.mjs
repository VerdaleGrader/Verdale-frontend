// Embeds content/legal/*.md into lib/legal-content.gen.ts so the pages never read the disk at runtime
// (Cloudflare Workers has no content/ folder). Run `npm run legal:generate` after editing a document.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const documents = ['terms', 'privacy'];

const entries = documents.map((key) => {
  const markdown = readFileSync(path.join(root, 'content', 'legal', `${key}.md`), 'utf8');
  return `  ${key}: ${JSON.stringify(markdown)},`;
});

const output = `// Generated by scripts/legal-content-generate.mjs from content/legal/*.md. Do not edit by hand.
export const LEGAL_MARKDOWN = {
${entries.join('\n')}
} as const;
`;

writeFileSync(path.join(root, 'lib', 'legal-content.gen.ts'), output);
